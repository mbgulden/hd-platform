#!/usr/bin/env node
// scripts/kpis/render-dashboard.mjs
// Render the static PWP dashboard page (humandesignengine.com/pwp/kpi-dashboard.html)
// from the latest aggregated KPI report.

import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const HERE = path.dirname(url.fileURLToPath(import.meta.url));

function escapeHtml(str) {
  return String(str ?? '').replace(/[&<>"']/g, (ch) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  })[ch]);
}

function render(report) {
  const sections = Object.values(report.collections).map((coll) => `
    <section>
      <h2>${escapeHtml(coll.title)}</h2>
      <table>
        <thead>
          <tr><th>Metric</th><th>Now</th><th>vs prior</th></tr>
        </thead>
        <tbody>
          ${coll.metrics.map((m) => `
            <tr>
              <td>${escapeHtml(m.label)}</td>
              <td class="num">${escapeHtml(m.formatted)}</td>
              <td class="delta ${m.delta_pct.startsWith('NEW') || m.delta_pct.startsWith('▲') ? 'up' : m.delta_pct.startsWith('▼') ? 'down' : 'flat'}">${escapeHtml(m.delta_pct)}</td>
            </tr>
          `).join('')}
        </tbody>
      </table>
    </section>
  `).join('\n');

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>HDE KPI Dashboard — ${escapeHtml(report.windowStartISO.slice(0, 10))}</title>
  <meta name="robots" content="noindex" />
  <link rel="canonical" href="https://humandesignengine.com/pwp/kpi-dashboard.html" />
  <style>
    :root { color-scheme: light; }
    body { font-family: -apple-system, "Inter", sans-serif; background: #FAF7F0; color: #2F3631; margin: 0; padding: 24px; }
    h1 { margin: 0 0 4px 0; font-weight: 600; }
    h2 { margin: 32px 0 8px; font-weight: 600; color: #2F3631; }
    .meta { color: #5C625E; font-size: 14px; }
    section { max-width: 720px; }
    table { border-collapse: collapse; width: 100%; margin-top: 8px; }
    th, td { padding: 8px 12px; border-bottom: 1px solid #eee; text-align: left; font-size: 14px; }
    th { background: rgba(95,114,97,0.08); color: #2F3631; font-weight: 600; }
    td.num { text-align: right; font-variant-numeric: tabular-nums; }
    td.delta { text-align: right; font-size: 12px; }
    td.up { color: #3F6B47; }
    td.down { color: #B4534A; }
    td.flat { color: #5C625E; }
    footer { margin-top: 32px; font-size: 12px; color: #8C8275; }
  </style>
</head>
<body>
  <h1>HDE KPI dashboard</h1>
  <p class="meta">Window ${escapeHtml(report.windowStartISO.slice(0, 16))} → ${escapeHtml(report.windowEndISO.slice(0, 16))} UTC · Generated ${escapeHtml(report.generatedAt)}</p>
  ${sections}
  <footer>
    Auto-generated by <code>scripts/kpis/cli.mjs</code>. Embed this URL into the existing PWP dashboard section <code>pwp/kpi-dashboard-section.html</code>.
  </footer>
</body>
</html>
`;
}

async function main() {
  const args = process.argv.slice(2);
  const reportPath = args[0];
  if (!reportPath || !fs.existsSync(reportPath)) {
    console.error('usage: node render-dashboard.mjs <report.json> [--out path/kpi-dashboard.html]');
    process.exit(2);
  }
  const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
  const html = render(report);
  const outIdx = args.indexOf('--out');
  const out = outIdx >= 0 ? args[outIdx + 1] : path.join(HERE, '..', '..', 'docs', 'pwp', 'kpi-dashboard.html');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
  console.log(`wrote ${out} (${html.length} bytes)`);
}

main().catch((err) => { console.error(err); process.exit(1); });
